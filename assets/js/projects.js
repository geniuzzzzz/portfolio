const ITEMS_PER_LOAD = 12;

let currentFilter = "all";
let currentSearch = "";
let visibleCount = ITEMS_PER_LOAD;


// dom

const projectGrid = document.getElementById("projectGrid");
const projectSearch = document.getElementById("projectSearch");
const projectResults = document.getElementById("projectResults");
const noProjects = document.getElementById("noProjects");
const loadMoreWrapper = document.getElementById("loadMoreWrapper");
const loadMoreBtn = document.getElementById("loadMoreBtn");
const resetProjects = document.getElementById("resetProjects");

const totalDesignCount = document.getElementById("totalDesignCount");
const electionCount = document.getElementById("electionCount");

const projectModal = document.getElementById("projectModal");
const modalBackdrop = document.getElementById("modalBackdrop");
const modalClose = document.getElementById("modalClose");
const modalImage = document.getElementById("modalImage");
const modalOrganization = document.getElementById("modalOrganization");
const modalTitle = document.getElementById("modalTitle");
const modalDescription = document.getElementById("modalDescription");




/////

function buildAssetPath(folder, file) {

    const encodedFolder = folder
        .split("/")
        .map(part => encodeURIComponent(part))
        .join("/");

    const encodedFile = encodeURIComponent(file);

    return `assets/img/${encodedFolder}/${encodedFile}`;
}


function formatTitle(filename) {

    return filename
        .replace(/\.[^/.]+$/, "")
        .replace(/_/g, " ")
        .replace(/-/g, " ")
        .replace(/\s+/g, " ")
        .replace(/\bcopy\b/gi, "")
        .trim();
}


function getDescription(project) {

    if (project.organization === "focitsalc") {
        return "Graphic design work created for FOCITSALC.";
    }

    if (project.organization === "ccc") {
        return "Graphic design work created for CCC.";
    }

    if (project.organization === "nacoss") {
        return "Graphic design work created for NACOSS.";
    }

    if (project.organization === "elections") {
        return "Election and campaign design work.";
    }

    return "Independent graphic design work.";
}





/////

function getFilteredProjects() {

    return projects.filter(project => {

        const matchesOrganization =
            currentFilter === "all" ||
            project.organization === currentFilter;

        const searchableText = `
            ${formatTitle(project.file)}
            ${project.organizationName}
        `.toLowerCase();

        const matchesSearch =
            !currentSearch ||
            searchableText.includes(currentSearch);

        return matchesOrganization && matchesSearch;

    });

}




//////

function renderProjects() {

    const filteredProjects = getFilteredProjects();

    const visibleProjects =
        filteredProjects.slice(0, visibleCount);

    projectGrid.innerHTML = "";

    if (filteredProjects.length === 0) {

        noProjects.classList.remove("d-none");
        loadMoreWrapper.classList.add("d-none");

        projectResults.textContent = "0 designs";

        return;
    }

    noProjects.classList.add("d-none");

    visibleProjects.forEach((project, index) => {

        const title = formatTitle(project.file);

        const card = document.createElement("div");

        card.className =
            "col-sm-6 col-lg-4 fade-in";

        card.innerHTML = `
            <article
                class="project-card"
                tabindex="0"
                role="button"
                data-project-index="${projects.indexOf(project)}">

                <div class="project-card-image">

                    <img
                        src="${buildAssetPath(project.folder, project.file)}"
                        alt="${title}"
                        loading="${index < 6 ? "eager" : "lazy"}">

                    <div class="project-card-overlay">

                        <span>
                            <i class="fas fa-expand"></i>
                            View Design
                        </span>

                    </div>

                </div>

                <div class="project-card-body">

                    <span class="project-organization">
                        ${project.organizationName}
                    </span>

                    <h3 class="project-card-title">
                        ${title}
                    </h3>

                </div>

            </article>
        `;

        projectGrid.appendChild(card);

    });


    projectResults.textContent =
        `${filteredProjects.length} design${filteredProjects.length === 1 ? "" : "s"}`;


    if (visibleCount < filteredProjects.length) {

        loadMoreWrapper.classList.remove("d-none");

    } else {

        loadMoreWrapper.classList.add("d-none");

    }


    attachCardEvents();

}





// card 

function attachCardEvents() {

    const cards =
        document.querySelectorAll(".project-card");

    cards.forEach(card => {

        card.addEventListener("click", () => {

            const index =
                Number(card.dataset.projectIndex);

            openProjectModal(projects[index]);

        });


        card.addEventListener("keydown", event => {

            if (
                event.key === "Enter" ||
                event.key === " "
            ) {

                event.preventDefault();

                const index =
                    Number(card.dataset.projectIndex);

                openProjectModal(projects[index]);

            }

        });

    });

}





// modal 

function openProjectModal(project) {

    const title = formatTitle(project.file);

    modalImage.src =
        buildAssetPath(project.folder, project.file);

    modalImage.alt = title;

    modalOrganization.textContent =
        project.organizationName;

    modalTitle.textContent =
        title;

    modalDescription.textContent =
        getDescription(project);

    projectModal.classList.add("active");

    projectModal.setAttribute(
        "aria-hidden",
        "false"
    );

    document.body.style.overflow = "hidden";

}


function closeProjectModal() {

    projectModal.classList.remove("active");

    projectModal.setAttribute(
        "aria-hidden",
        "true"
    );

    document.body.style.overflow = "";

    modalImage.src = "";

}




// filter 

document
    .querySelectorAll("#organizationFilters .filter-btn")
    .forEach(button => {

        button.addEventListener("click", () => {

            document
                .querySelectorAll(
                    "#organizationFilters .filter-btn"
                )
                .forEach(btn =>
                    btn.classList.remove("active")
                );

            button.classList.add("active");

            currentFilter =
                button.dataset.filter;

            visibleCount =
                ITEMS_PER_LOAD;

            renderProjects();

        });

    });




// search 

if (projectSearch) {

    projectSearch.addEventListener("input", event => {

        currentSearch =
            event.target.value
                .trim()
                .toLowerCase();

        visibleCount =
            ITEMS_PER_LOAD;

        renderProjects();

    });

}




// more 

if (loadMoreBtn) {

    loadMoreBtn.addEventListener("click", () => {

        visibleCount += ITEMS_PER_LOAD;

        renderProjects();

    });

}



// reset 

function resetAllFilters() {

    currentFilter = "all";
    currentSearch = "";
    visibleCount = ITEMS_PER_LOAD;

    if (projectSearch) {
        projectSearch.value = "";
    }

    document
        .querySelectorAll(
            "#organizationFilters .filter-btn"
        )
        .forEach(button => {

            button.classList.toggle(
                "active",
                button.dataset.filter === "all"
            );

        });

    renderProjects();

}


if (resetProjects) {

    resetProjects.addEventListener(
        "click",
        resetAllFilters
    );

}




//////

if (modalClose) {
    modalClose.addEventListener(
        "click",
        closeProjectModal
    );
}

if (modalBackdrop) {
    modalBackdrop.addEventListener(
        "click",
        closeProjectModal
    );
}


document.addEventListener("keydown", event => {

    if (
        event.key === "Escape" &&
        projectModal.classList.contains("active")
    ) {

        closeProjectModal();

    }

});




// counter 

function updateCounters() {

    if (totalDesignCount) {

        totalDesignCount.textContent =
            projects.length + "+";

    }


    if (electionCount) {

        electionCount.textContent =
            projects.filter(
                project => project.organization === "elections"
            ).length;

    }

}




updateCounters();
renderProjects();